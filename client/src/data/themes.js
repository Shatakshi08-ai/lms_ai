function theme({
  id,
  name,
  dark = false,
  primary,
  secondary,
  accent,
  background,
  surface,
  text,
  muted,
  border,
  navbar,
  sidebar,
  sidebarText,
  hover,
  active,
  button = primary,
  buttonText = '#ffffff',
}) {
  return {
    id,
    name,
    dark,
    tokens: {
      '--primary-color': primary,
      '--secondary-color': secondary,
      '--accent-color': accent,
      '--background-color': background,
      '--surface-color': surface,
      '--text-color': text,
      '--muted-text': muted,
      '--border-color': border,
      '--navbar-bg': navbar,
      '--sidebar-bg': sidebar,
      '--sidebar-text': sidebarText,
      '--sidebar-hover': hover,
      '--sidebar-active': active,
      '--button-bg': button,
      '--button-text': buttonText,
      '--card-shadow': dark ? '0 12px 28px rgba(0,0,0,0.35)' : '0 10px 24px rgba(60,40,30,0.08)',
      '--light-pink': '#f0d4d5',
      '--tan': secondary,
      '--yellow': accent,
      '--pastel-red': active,
    },
    antd: {
      colorPrimary: primary,
      colorInfo: secondary,
      colorSuccess: '#5d7a4a',
      colorWarning: accent,
      colorError: active,
      colorLink: primary,
    },
  };
}

